/* Keypad row pin definitions
 * Rows are connected to GPIO pins P1.16 to P1.19.
 */

#define ROW0 16 //ROW0 - p1.16
#define ROW1 17 //ROW1 - p1.17
#define ROW2 18 //ROW2 - p1.18
#define ROW3 19 //ROW3 - p1.19

/* Keypad column pin definitions
 * Columns are connected to GPIO pins P1.20 to P1.23.
 */

#define COL0 20 //COLUMN0 - p1.20
#define COL1 21 //COLUMN1 - p1.21
#define COL2 22 //COLUMN2 - p1.22
#define COL3 23 //COLUMN3 - p1.23

